"""
Report generation for Q-Shield.

Generates professional PDF and CSV reports from current assessment data.
Reports are generated from live data, not static templates.
"""

import io
import csv
from datetime import datetime, timezone
from typing import List, Dict, Optional

from qshield.models import NIST_PQC_STANDARDS, DEFAULT_SCORING_CONFIG


def generate_csv_report(
    assets: List[dict],
    findings: List[dict],
    scores: List[dict],
) -> str:
    """Generate a combined CSV assessment report."""
    output = io.StringIO()
    writer = csv.writer(output)

    # Header
    writer.writerow([
        "Asset ID", "Asset Name", "Type", "Domain", "Environment",
        "Algorithm", "Purpose", "Protocol", "Data Sensitivity",
        "Business Criticality", "Internet Exposed", "Dependency Count",
        "Migration Status", "Risk Score", "Risk Level",
        "Quantum Vulnerable", "PQC Algorithm", "Needs Review",
        "Vulnerability Type", "Evidence", "Recommendation",
    ])

    finding_map = {f.get("asset_id", ""): f for f in findings}
    score_map = {s.get("asset_id", ""): s for s in scores}

    for asset in assets:
        aid = asset.get("asset_id", "")
        f = finding_map.get(aid, {})
        s = score_map.get(aid, {})

        writer.writerow([
            aid,
            asset.get("asset_name", ""),
            asset.get("asset_type", ""),
            asset.get("business_domain", ""),
            asset.get("environment", ""),
            asset.get("cryptographic_algorithm", ""),
            asset.get("cryptographic_purpose", ""),
            asset.get("protocol", ""),
            asset.get("data_sensitivity", ""),
            asset.get("business_criticality", ""),
            asset.get("internet_exposed", ""),
            asset.get("dependency_count", ""),
            asset.get("migration_status", ""),
            s.get("total_score", ""),
            s.get("risk_level", ""),
            f.get("is_quantum_vulnerable", ""),
            f.get("is_pqc", ""),
            f.get("needs_review", ""),
            f.get("vulnerability_type", ""),
            f.get("evidence", ""),
            f.get("recommendation", ""),
        ])

    return output.getvalue()


def generate_pdf_report(
    assets: List[dict],
    findings: List[dict],
    scores: List[dict],
    recommendations: List[dict],
    summary_stats: dict,
) -> bytes:
    """Generate a professional PDF assessment report."""
    from fpdf import FPDF

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=20)

    # ── Cover Page ───────────────────────────────────────────────────
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 28)
    pdf.ln(40)
    pdf.cell(0, 15, "Q-Shield", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 14)
    pdf.cell(0, 10, "Quantum-Readiness Assessment Report", align="C",
             new_x="LMARGIN", new_y="NEXT")
    pdf.ln(10)
    pdf.set_font("Helvetica", "", 11)
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    pdf.cell(0, 8, f"Generated: {now}", align="C",
             new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 8, f"Assets Assessed: {summary_stats.get('total_assets', 0)}",
             align="C", new_x="LMARGIN", new_y="NEXT")

    pdf.ln(20)
    pdf.set_font("Helvetica", "I", 9)
    pdf.multi_cell(0, 5, (
        "DISCLAIMER: This report is generated by Q-Shield, a prototype "
        "assessment tool. Scores are decision-support estimates, not "
        "certified security ratings. All findings require review by "
        "qualified security professionals before action. This tool does "
        "not certify compliance with any standard or framework."
    ))

    # ── Executive Summary ────────────────────────────────────────────
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 12, "Executive Summary", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)
    pdf.set_font("Helvetica", "", 11)

    stats = summary_stats
    summary_lines = [
        f"Total assets assessed: {stats.get('total_assets', 0)}",
        f"Assets with quantum-vulnerable cryptography: {stats.get('quantum_vulnerable', 0)}",
        f"High/Critical priority assets: {stats.get('high_priority', 0)}",
        f"Assets using PQC algorithms: {stats.get('pqc_assets', 0)}",
        f"Assets requiring manual review: {stats.get('needs_review', 0)}",
    ]
    for line in summary_lines:
        pdf.cell(0, 7, f"  * {line}", new_x="LMARGIN", new_y="NEXT")

    # ── Risk Distribution ────────────────────────────────────────────
    pdf.ln(8)
    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(0, 10, "Risk Distribution", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)

    risk_counts = {"Critical": 0, "High": 0, "Medium": 0, "Low": 0, "Unknown": 0}
    for s in scores:
        level = s.get("risk_level", "Unknown")
        risk_counts[level] = risk_counts.get(level, 0) + 1

    for level, count in risk_counts.items():
        if count > 0:
            pdf.cell(0, 6, f"  {level}: {count} asset(s)",
                     new_x="LMARGIN", new_y="NEXT")

    # ── Asset Findings ───────────────────────────────────────────────
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 12, "Asset Findings", new_x="LMARGIN", new_y="NEXT")

    finding_map = {f.get("asset_id", ""): f for f in findings}
    score_map = {s.get("asset_id", ""): s for s in scores}

    for asset in assets:
        aid = asset.get("asset_id", "")
        f = finding_map.get(aid, {})
        s = score_map.get(aid, {})

        pdf.ln(4)
        pdf.set_font("Helvetica", "B", 12)
        name = f"{asset.get('asset_name', aid)} ({aid})"
        pdf.cell(0, 8, _safe_str(name), new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("Helvetica", "", 9)
        details = [
            f"Algorithm: {asset.get('cryptographic_algorithm', 'N/A')}",
            f"Purpose: {asset.get('cryptographic_purpose', 'N/A')}",
            f"Risk Score: {s.get('total_score', 'N/A')} ({s.get('risk_level', 'N/A')})",
            f"Quantum Vulnerable: {'Yes' if f.get('is_quantum_vulnerable') else 'No'}",
            f"PQC: {'Yes' if f.get('is_pqc') else 'No'}",
            f"Confidence: {f.get('confidence', 'N/A')}",
            f"Rule: {f.get('rule_id', 'N/A')}",
        ]
        for d in details:
            pdf.cell(0, 5, f"  {_safe_str(d)}", new_x="LMARGIN", new_y="NEXT")

        evidence = f.get("evidence", "")
        if evidence:
            pdf.set_font("Helvetica", "I", 8)
            pdf.multi_cell(0, 4, f"  Evidence: {_safe_str(evidence[:300])}")

        # Check if we need a new page
        if pdf.get_y() > 250:
            pdf.add_page()

    # ── Migration Recommendations ────────────────────────────────────
    if recommendations:
        pdf.add_page()
        pdf.set_font("Helvetica", "B", 18)
        pdf.cell(0, 12, "Migration Recommendations", new_x="LMARGIN", new_y="NEXT")

        for rec in recommendations[:20]:  # Limit for PDF size
            pdf.ln(3)
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(0, 7, _safe_str(
                f"{rec.get('asset_name', '')} - {rec.get('risk_priority', '')}"
            ), new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 9)
            if rec.get("target_standard"):
                pdf.cell(0, 5, f"  Target: {_safe_str(rec['target_standard'])}",
                         new_x="LMARGIN", new_y="NEXT")
            for action in rec.get("suggested_actions", [])[:3]:
                pdf.cell(0, 5, f"  - {_safe_str(str(action)[:100])}",
                         new_x="LMARGIN", new_y="NEXT")
            if pdf.get_y() > 250:
                pdf.add_page()

    # ── Methodology ──────────────────────────────────────────────────
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 12, "Methodology", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    pdf.multi_cell(0, 5, _safe_str(DEFAULT_SCORING_CONFIG["disclaimer"]))
    pdf.ln(4)

    weights = DEFAULT_SCORING_CONFIG["weights"]
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 7, "Scoring Weights:", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    for name, weight in weights.items():
        pdf.cell(0, 5, f"  {name.replace('_', ' ').title()}: {weight:.0%}",
                 new_x="LMARGIN", new_y="NEXT")

    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 7, "Standards References:", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    for fips, info in NIST_PQC_STANDARDS.items():
        pdf.cell(0, 5, f"  {fips}: {_safe_str(info['title'])}",
                 new_x="LMARGIN", new_y="NEXT")

    # ── Limitations ──────────────────────────────────────────────────
    pdf.ln(6)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 7, "Limitations:", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 8)
    limitations = [
        "This is a prototype assessment tool, not a production security system.",
        "Risk scores are estimates for planning, not certified ratings.",
        "Detection is rule-based and may not cover all cryptographic configurations.",
        "AI recommendations require human review before implementation.",
        "This report does not certify compliance with any standard.",
        "Cryptographic detection analyzes declared algorithms, not live traffic.",
    ]
    for lim in limitations:
        pdf.cell(0, 4, f"  - {lim}", new_x="LMARGIN", new_y="NEXT")

    return pdf.output()


def _safe_str(text) -> str:
    """Ensure text is safe for PDF output (latin-1 compatible)."""
    if not isinstance(text, str):
        text = str(text)
    return text.encode("latin-1", errors="replace").decode("latin-1")
